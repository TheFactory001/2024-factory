ex_1 = False
ex_2 = 29
ex_3 = 4.1352

print(type(ex_1))   # Identify the data type in the parenthesis
print(type(ex_2))
print(type(ex_3))


ex_4 = str(True)     # Str() is used to convert value in parenthesis to a string
ex_5 = str(5)
ex_6 = str(3.21)

print(type(ex_4))
print(type(ex_5))
print(type(ex_6))
