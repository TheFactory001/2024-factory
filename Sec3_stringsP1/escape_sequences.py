## Escape sequences - Special characters used in strings

print("This\tis\ta\tlot\tof\tspace.")     # \t used to make a horizontal space or indent when working with strings


print('line one\nline two')               # \n newline


print('"When I said \'immediately,\'I meant today!" said King Saul.')     # \' and \" Putting quotes in your string
print("\"Do or do not. There is no try.\"")

print("All escape sequences contain a \\.")                               # \\ used for backslash \ in a string