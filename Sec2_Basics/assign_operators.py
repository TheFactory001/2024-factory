# Assignment Operators are used for reassignment
add_assign = 5
add_assign += 7

# Subtraction
sub = 10
sub -= 5          # Result is 5

# multiplication
mult = 10
mult *= 5          # Result is 50

# Division
div = 10
div /= 5          # Result is 2.0

# Exponentiation
exp = 10
exp **= 2          # Result is 100

# floor division
floor = 10
floor //= 6          # Result is 1

# modulo
mod = 10
mod %= 7          # Result is 3

print(mod)
print(add_assign)
print(floor)
print(exp)
print(div)
print(mult)

